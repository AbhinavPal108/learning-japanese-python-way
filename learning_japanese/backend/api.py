"""Versioned REST API, including guarded partner-project data exchange."""
from __future__ import annotations

import hmac
from typing import Any
from fastapi import APIRouter, Depends, Header, HTTPException, Query

from learning_japanese.config import PARTNER_API_KEY, PROJECT_ID
from learning_japanese.models.schemas import (
    LearningEventIn, PartnerEventIn, PracticeAttemptIn, QuizStartIn, QuizSubmitIn,
)
from learning_japanese.services import learning_service
from learning_japanese.services.number_service import all_numbers, number_details

router = APIRouter(prefix="/api/v1", tags=["Learning Japanese API v1"])


def require_partner_key(x_partner_api_key: str | None = Header(default=None, alias="X-Partner-API-Key")) -> None:
    """If a shared key is configured, require it on partner endpoints."""
    if PARTNER_API_KEY and not hmac.compare_digest(x_partner_api_key or "", PARTNER_API_KEY):
        raise HTTPException(status_code=401, detail="Missing or invalid X-Partner-API-Key")


@router.get("/health")
def health() -> dict[str, str]:
    return {"status": "ok", "service": PROJECT_ID, "api_version": "v1"}


@router.get("/numbers")
def list_numbers() -> dict[str, Any]:
    return {"count": 100, "items": all_numbers()}


@router.get("/numbers/{number}")
def get_number(number: int) -> dict[str, Any]:
    try:
        return number_details(number)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc


@router.post("/learning-events", status_code=201)
def create_learning_event(body: LearningEventIn) -> dict[str, Any]:
    try:
        return learning_service.record_learning_event(
            body.learner_id, body.event_type, body.number, body.payload, body.source_project
        )
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc


@router.post("/practice/attempts", status_code=201)
def save_practice_attempt(body: PracticeAttemptIn) -> dict[str, Any]:
    return learning_service.record_practice_attempt(
        body.learner_id, body.question_number, body.selected_number, body.source_project
    )


@router.post("/quizzes/start", status_code=201)
def start_quiz(body: QuizStartIn) -> dict[str, Any]:
    try:
        return learning_service.create_quiz(body.learner_id, body.num_questions, body.source_project)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc


@router.post("/quizzes/{quiz_id}/submit")
def submit_quiz(quiz_id: str, body: QuizSubmitIn) -> dict[str, Any]:
    try:
        return learning_service.submit_quiz(quiz_id, [answer.model_dump() for answer in body.answers])
    except KeyError as exc:
        raise HTTPException(status_code=404, detail=str(exc).strip("'")) from exc
    except ValueError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc


@router.get("/quizzes/results/{learner_id}")
def quiz_results(learner_id: str) -> dict[str, Any]:
    progress = learning_service.get_progress(learner_id)
    return {"learner_id": learner_id, "count": len(progress["recent_quizzes"]),
            "results": progress["recent_quizzes"]}


@router.get("/quizzes/result/{quiz_id}")
def quiz_result(quiz_id: str) -> dict[str, Any]:
    result = learning_service.get_quiz_result(quiz_id)
    if result is None:
        raise HTTPException(status_code=404, detail="Quiz not found")
    return result


@router.get("/progress/{learner_id}")
def learner_progress(learner_id: str) -> dict[str, Any]:
    return learning_service.get_progress(learner_id)


@router.get("/partner/export/{learner_id}", dependencies=[Depends(require_partner_key)])
def export_partner_data(learner_id: str) -> dict[str, Any]:
    """Share a learner's summary, quiz results, practice attempts, and learning events."""
    return {
        "schema_version": "1.0",
        "source_project": PROJECT_ID,
        "exported_learner_id": learner_id,
        **learning_service.get_progress(learner_id),
    }


@router.post("/partner/events", status_code=201, dependencies=[Depends(require_partner_key)])
def receive_partner_event(body: PartnerEventIn) -> dict[str, Any]:
    """Accept an event generated by the companion project and store its provenance."""
    try:
        stored = learning_service.record_learning_event(
            learner_id=body.learner_id,
            event_type=f"partner:{body.event_type}",
            payload=body.payload,
            source_project=body.source_project,
        )
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    return {"accepted": True, **stored}
